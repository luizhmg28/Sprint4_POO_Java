CREATE SEQUENCE SEQ_TRECHO_RODOVIA START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EQUIPE_MANUTENCAO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENCAO_OPERACIONAL START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_RELATORIO_PRIORIDADE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE EQUIPE_MANUTENCAO (
    ID NUMBER DEFAULT SEQ_EQUIPE_MANUTENCAO.NEXTVAL PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    ESPECIALIDADE VARCHAR2(80) NOT NULL,
    QUANTIDADE_INTEGRANTES NUMBER(3) NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    CONSTRAINT CK_EQUIPE_STATUS CHECK (STATUS IN ('ATIVA', 'INATIVA', 'EM_CAMPO'))
);

CREATE TABLE TRECHO_RODOVIA (
    ID NUMBER DEFAULT SEQ_TRECHO_RODOVIA.NEXTVAL PRIMARY KEY,
    KM_INICIAL NUMBER(6) NOT NULL,
    KM_FINAL NUMBER(6) NOT NULL,
    ALTURA_VEGETACAO NUMBER(6,2) NOT NULL,
    TIPO_AMBIENTE VARCHAR2(30) NOT NULL,
    ACESSO_DIFICIL CHAR(1) DEFAULT 'N' NOT NULL,
    CODIGO_SENSOR NUMBER(10),
    MONITORADO_IOT CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT CK_TRECHO_ACESSO CHECK (ACESSO_DIFICIL IN ('S', 'N')),
    CONSTRAINT CK_TRECHO_IOT CHECK (MONITORADO_IOT IN ('S', 'N')),
    CONSTRAINT CK_TRECHO_KM CHECK (KM_FINAL > KM_INICIAL),
    CONSTRAINT CK_TRECHO_SENSOR CHECK (
        (MONITORADO_IOT = 'S' AND CODIGO_SENSOR IS NOT NULL)
        OR (MONITORADO_IOT = 'N')
    )
);

CREATE TABLE INTERVENCAO_OPERACIONAL (
    ID NUMBER DEFAULT SEQ_INTERVENCAO_OPERACIONAL.NEXTVAL PRIMARY KEY,
    TRECHO_ID NUMBER NOT NULL,
    EQUIPE_ID NUMBER NOT NULL,
    TIPO_SERVICO VARCHAR2(80) NOT NULL,
    PRIORIDADE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    DATA_PROGRAMADA DATE NOT NULL,
    OBSERVACAO VARCHAR2(300),
    CONSTRAINT FK_INTERVENCAO_TRECHO FOREIGN KEY (TRECHO_ID)
        REFERENCES TRECHO_RODOVIA (ID),
    CONSTRAINT FK_INTERVENCAO_EQUIPE FOREIGN KEY (EQUIPE_ID)
        REFERENCES EQUIPE_MANUTENCAO (ID),
    CONSTRAINT CK_INTERVENCAO_PRIORIDADE CHECK (PRIORIDADE IN ('URGENTE', 'CRITICO', 'ATENCAO', 'NORMAL')),
    CONSTRAINT CK_INTERVENCAO_STATUS CHECK (STATUS IN ('PROGRAMADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA'))
);

CREATE TABLE RELATORIO_PRIORIDADE (
    ID NUMBER DEFAULT SEQ_RELATORIO_PRIORIDADE.NEXTVAL PRIMARY KEY,
    DATA_GERACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    QT_URGENTE NUMBER(5) DEFAULT 0 NOT NULL,
    QT_CRITICO NUMBER(5) DEFAULT 0 NOT NULL,
    QT_ATENCAO NUMBER(5) DEFAULT 0 NOT NULL,
    QT_NORMAL NUMBER(5) DEFAULT 0 NOT NULL,
    RESUMO CLOB NOT NULL
);

-- Executar com a API e outros escritores parados.

DECLARE
    proximo NUMBER;
    identidade NUMBER;
    existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO identidade FROM USER_TAB_IDENTITY_COLS
    WHERE TABLE_NAME = 'TRECHO_RODOVIA' AND COLUMN_NAME = 'ID';
    SELECT COUNT(*) INTO existe FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_TRECHO_RODOVIA';
    IF existe = 0 THEN
        SELECT NVL(MAX(ID), 0) + 1 INTO proximo FROM TRECHO_RODOVIA;
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_TRECHO_RODOVIA START WITH '
            || TO_CHAR(proximo, 'FM9999999999999999999999999999')
            || ' INCREMENT BY 1 NOCACHE';
    END IF;
    IF identidade > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TRECHO_RODOVIA MODIFY ID DROP IDENTITY';
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE TRECHO_RODOVIA MODIFY (ID DEFAULT SEQ_TRECHO_RODOVIA.NEXTVAL)';
END;
/

